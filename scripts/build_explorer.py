#!/usr/bin/env python3
"""Build the offline explorer from the companion's existing, fixed records."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "papers": "papers/README.md",
    "scope": "analysis/data/analysis-scope.json",
    "settings": "analysis/data/overlap/relationships/source-records.json",
    "strict": "analysis/data/overlap/relationships/outputs/strict-analysis-records.json",
    "roles": "analysis/data/overlap/roles/proposed-assignments.json",
    "audit": "analysis/data/benchmarks/benchmark-audit.json",
    "names": "site/paper-names.json",
}
GROUPS = [
    "Interpretation", "Answerability", "Consequence and verification",
    "Action and interaction", "Context and user adaptation", "Related surveys",
]


def build(root=ROOT):
    raw = {key: (root / path).read_bytes() for key, path in SOURCES.items()}
    data = {key: json.loads(value) for key, value in raw.items() if key != "papers"}
    papers = []
    group = None
    for line in raw["papers"].decode("utf-8").splitlines():
        if line.startswith("## "):
            group = line[3:]
        if not re.match(r"\| \d{4} \|", line):
            continue
        if group not in GROUPS:
            raise ValueError(f"Unrecognized reading group: {group}")
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        links = re.findall(r"\[([^\]]+)\]\((https?://[^)]+)\)", cells[1])
        identifier = re.search(r"`([^`]+)`", cells[2])
        if not links or not identifier:
            raise ValueError(f"Cannot parse paper row: {line}")
        paper_id = identifier[1]
        scope = ("survey" if group == "Related surveys" else
                 "analysis" if paper_id in data["scope"]["analysis_source_paper_ids"]
                 else "literature")
        papers.append({
            "id": paper_id, "name": data["names"][paper_id], "year": int(cells[0]), "title": links[0][0],
            "url": links[0][1], "links": [{"label": label, "url": url} for label, url in links],
            "group": group, "scope": scope,
            "exclusion": data["scope"]["excluded_literature"].get(paper_id),
            "settings": [], "audits": [],
        })
    by_id = {paper["id"]: paper for paper in papers}
    if len(by_id) != len(papers):
        raise ValueError("Duplicate paper ID")
    if set(by_id) != set(data["names"]) or any(not isinstance(n, str) or not n.strip() for n in data["names"].values()):
        raise ValueError("Paper display names must cover exactly the reading list")
    if {p["id"] for p in papers if p["scope"] == "analysis"} != set(data["scope"]["analysis_source_paper_ids"]):
        raise ValueError("Reading list and analysis scope disagree")
    strict = {row["setting_id"]: row for row in data["strict"]}
    roles = {row["setting_id"]: row for row in data["roles"]}
    settings = data["settings"]["settings"]
    if len(settings) != data["scope"]["direct_nl2sql_settings"] or {s["setting_id"] for s in settings} != set(strict):
        raise ValueError("Setting populations disagree")
    for setting in settings:
        sid = setting["setting_id"]
        row = strict[sid]
        if any(setting["perspectives"][key]["status"] != row["states"][key] for key in "IBCA"):
            raise ValueError(f"Endpoint records disagree: {sid}")
        # Retain the reviewed counts and original rationale separately; the latter
        # is not a substitute for the strict, resolved relationship assignments.
        by_id[setting["paper_id"]]["settings"].append({
            **setting, "states": row["states"], "connections": row["connections"],
            "verification": roles[sid]["verification"],
        })
    if len(data["audit"]["records"]) != data["scope"]["benchmark_audit_settings"]:
        raise ValueError("Benchmark population disagrees with scope")
    for audit in data["audit"]["records"]:
        by_id[audit["citation_key"]]["audits"].append(audit)
    return {
        "schemaVersion": 1, "groups": GROUPS, "scope": data["scope"],
        "provenance": [{"path": SOURCES[key], "sha256": hashlib.sha256(value).hexdigest()} for key, value in raw.items()],
        "annotationProvenance": data["settings"]["annotation_provenance"],
        "auditQualifications": data["audit"]["qualifications"], "papers": papers,
    }


def serialized(data):
    # A local JS payload avoids fetch/CORS and works when index.html is opened
    # directly. Escape HTML delimiters defensively if a title contains markup.
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return "// Generated by scripts/build_explorer.py; do not edit.\nwindow.SURVEY_DATA = " + payload + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed site data is stale")
    args = parser.parse_args()
    expected = serialized(build())
    target = ROOT / "site/data.js"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Explorer data is stale; run python3 scripts/build_explorer.py\n")
        print(f"Explorer data matches all {len(SOURCES)} source files.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        print(f"Built {target.relative_to(ROOT)} ({len(expected.encode('utf-8')):,} bytes)")
